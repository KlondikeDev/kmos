"""Emit a small C header identifying a rolling build, without an OS version."""
import datetime
import os
import subprocess


def build_id():
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    date = (datetime.datetime.fromtimestamp(int(epoch), datetime.timezone.utc)
            if epoch else datetime.datetime.now(datetime.timezone.utc))
    source = subprocess.check_output(["git", "rev-parse", "--short=12", "HEAD"], text=True).strip()
    dirty = subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=normal"], text=True)
    return date.strftime("%Y%m%dT%H%M%SZ") + "-" + source + ("-dirty" if dirty else "")


